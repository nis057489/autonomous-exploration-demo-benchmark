#!/usr/bin/env python3
"""Generate long_t's collision world, overview, and evaluation geometry.

All geometry is a union of axis-aligned floor rectangles on a 0.5 m grid.
Walls follow the exposed boundary only, so junctions cannot acquire seams.
No external meshes, procedural randomness, or transport-dependent geometry.
"""

import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'simulation/worlds/long_t'
STEP = 0.5
WALL_THICKNESS = 0.2
WALL_HEIGHT = 2.0
STARTS = [dict(x=x, y=16.0, yaw=-1.5707963267948966) for x in (-4.0, 0.0, 4.0)]


def regions():
    result = [dict(name='transfer_hall', bounds=[-7, -2, 7, 2], role='transit'),
              dict(name='work_spine', bounds=[-1.5, -38, 1.5, 0], role='transit')]
    for i, x in enumerate((-4, 0, 4), 1):
        result.append(dict(name=f'start_{i}', bounds=[x - 1.5, 0, x + 1.5, 18], role='start'))
    # Six jobs behind corners. Unequal lengths create further decisions while
    # peers are still working; no robot is assigned a work branch in advance.
    for i, y in enumerate((-10, -22, -34), 1):
        for side, x, depth in [('left', -14, 6), ('right', 18, 8)]:
            result.extend([
                dict(name=f'work_{i}_{side}_entry', role='work',
                     bounds=[min(0, x) - 1.5, y - 1.5, max(0, x) + 1.5, y + 1.5]),
                dict(name=f'work_{i}_{side}_tip', role='work',
                     bounds=[x - 1.5, y - depth, x + 1.5, y]),
            ])
    return result


def floor_cells():
    cells = set()
    for region in regions():
        x0, y0, x1, y1 = [round(v / STEP) for v in region['bounds']]
        cells.update((x, y) for x in range(x0, x1) for y in range(y0, y1))
    return cells


def runs(values):
    values = sorted(values)
    if not values:
        return
    start = previous = values[0]
    for value in values[1:]:
        if value != previous + 1:
            yield start, previous + 1
            start = value
        previous = value
    yield start, previous + 1


def wall_boxes(cells):
    # Key includes outward normal; thickness lies entirely outside free floor.
    edges = {}
    for x, y in cells:
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            if (x + dx, y + dy) in cells:
                continue
            axis, line, along, sign = ('v', x + (dx > 0), y, dx) if dx else (
                'h', y + (dy > 0), x, dy)
            edges.setdefault((axis, line, sign), []).append(along)
    boxes = []
    for (axis, line, sign), values in sorted(edges.items()):
        for start, end in runs(values):
            across = line * STEP + sign * WALL_THICKNESS / 2
            along = (start + end) * STEP / 2
            length = (end - start) * STEP + WALL_THICKNESS
            boxes.append((across, along, WALL_THICKNESS, length) if axis == 'v'
                         else (along, across, length, WALL_THICKNESS))
    return boxes


def add_box(link, name, x, y, z, sx, sy, sz, color):
    for kind in ('collision', 'visual'):
        item = ET.SubElement(link, kind, name=f'{name}_{kind}')
        ET.SubElement(item, 'pose').text = f'{x:g} {y:g} {z:g} 0 0 0'
        box = ET.SubElement(ET.SubElement(item, 'geometry'), 'box')
        ET.SubElement(box, 'size').text = f'{sx:g} {sy:g} {sz:g}'
        if kind == 'visual':
            material = ET.SubElement(item, 'material')
            ET.SubElement(material, 'ambient').text = color
            ET.SubElement(material, 'diffuse').text = color


def world_xml():
    sdf = ET.Element('sdf', version='1.9')
    world = ET.SubElement(sdf, 'world', name='long_t_branch_exchange')
    world.append(ET.Comment(' Generated by tools/generate_long_t.py; see README.md for experiment assumptions. '))
    physics = ET.SubElement(world, 'physics', name='1ms', type='ode')
    ET.SubElement(physics, 'max_step_size').text = '0.001'
    ET.SubElement(physics, 'real_time_factor').text = '1.0'
    for library, name in [('physics', 'Physics'), ('sensors', 'Sensors'), ('imu', 'Imu'),
                          ('contact', 'Contact'), ('user-commands', 'UserCommands'),
                          ('scene-broadcaster', 'SceneBroadcaster')]:
        plugin = ET.SubElement(world, 'plugin', filename=f'gz-sim-{library}-system', name=f'gz::sim::systems::{name}')
        if library == 'sensors':
            ET.SubElement(plugin, 'render_engine').text = 'ogre2'
    scene = ET.SubElement(world, 'scene')
    ET.SubElement(scene, 'ambient').text = '0.75 0.75 0.75 1'
    ET.SubElement(scene, 'background').text = '0.72 0.80 0.90 1'
    ET.SubElement(scene, 'shadows').text = 'false'
    sun = ET.SubElement(world, 'light', name='sun', type='directional')
    for tag, value in [('pose', '0 0 30 0 0 0'), ('diffuse', '0.9 0.9 0.9 1'),
                       ('specular', '0.2 0.2 0.2 1'), ('direction', '-0.5 0.2 -1'),
                       ('cast_shadows', 'false')]:
        ET.SubElement(sun, tag).text = value
    for i, y in enumerate((12, 0, -12, -24, -36)):
        light = ET.SubElement(world, 'light', name=f'fill_{i}', type='point')
        ET.SubElement(light, 'pose').text = f'0 {y} 5 0 0 0'
        ET.SubElement(light, 'diffuse').text = '1 0.98 0.92 1'
        ET.SubElement(light, 'cast_shadows').text = 'false'
        attenuation = ET.SubElement(light, 'attenuation')
        for tag, value in [('range', '30'), ('constant', '0.4'), ('linear', '0.02'), ('quadratic', '0.002')]:
            ET.SubElement(attenuation, tag).text = value
    model = ET.SubElement(world, 'model', name='branch_exchange')
    ET.SubElement(model, 'static').text = 'true'
    floor = ET.SubElement(model, 'link', name='floor')
    cells = floor_cells()
    # Non-overlapping row strips: no duplicate coplanar collision surfaces.
    strips = {}
    for y in sorted({y for _, y in cells}):
        for x0, x1 in runs(x for x, cy in cells if cy == y):
            strips.setdefault((x0, x1), []).append(y)
    index = 0
    for (x0, x1), ys in sorted(strips.items()):
        for y0, y1 in runs(ys):
            add_box(floor, f'floor_{index}', (x0 + x1) * STEP / 2, (y0 + y1) * STEP / 2,
                    -0.1, (x1 - x0) * STEP, (y1 - y0) * STEP, 0.2, '0.36 0.38 0.42 1')
            index += 1
    walls = ET.SubElement(model, 'link', name='walls')
    for i, (x, y, sx, sy) in enumerate(wall_boxes(cells)):
        add_box(walls, f'wall_{i}', x, y, WALL_HEIGHT / 2, sx, sy, WALL_HEIGHT, '0.82 0.82 0.78 1')
    ET.indent(sdf, space='  ')
    return '<?xml version="1.0" ?>\n' + ET.tostring(sdf, encoding='unicode') + '\n'


def overview_svg():
    scale = 10
    def xy(x, y):
        return (x + 23) * scale, (23 - y) * scale
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="520" height="750" viewBox="0 0 520 750">',
           '<rect width="520" height="750" fill="#16202b"/>',
           '<g font-family="sans-serif" font-size="12" fill="white">',
           '<text x="20" y="22">long_t: branch exchange / 3 robots</text>']
    for region in regions():
        x0, y0, x1, y1 = region['bounds']
        x, y = xy(x0, y1)
        color = {'start': '#e7ae56', 'transit': '#c1ccd7', 'work': '#63b8ba'}[region['role']]
        svg.append(f'<rect x="{x}" y="{y}" width="{(x1-x0)*scale}" height="{(y1-y0)*scale}" fill="{color}"/>')
    for i, start in enumerate(STARTS, 1):
        x, y = xy(start['x'], start['y'])
        svg.extend([f'<circle cx="{x}" cy="{y}" r="7" fill="#254578"/>',
                    f'<text x="{x-7}" y="{y-12}" fill="#ffffff">R{i}</text>',
                    f'<path d="M {x} {y+9} v 18 l -4 -6 m 4 6 l 4 -6" fill="none" stroke="#254578" stroke-width="2"/>'])
    for i, cy in enumerate((-10, -22, -34), 1):
        for label, cx in [('L', -10), ('R', 12)]:
            x, y = xy(cx, cy)
            svg.append(f'<text x="{x-8}" y="{y+4}" fill="#102c32">{i}{label}</text>')
    svg.extend(['<text x="20" y="688">Amber: each robot surveys its own start branch</text>',
                '<text x="20" y="708">Teal: six untouched jobs beyond the transfer hall</text>',
                '<text x="20" y="728">3 m corridors; north is up; geometry shown to scale</text>', '</g></svg>'])
    return '\n'.join(svg) + '\n'


def artifacts():
    cells = floor_cells()
    metadata = dict(name='long_t_branch_exchange_v1', units='metres',
                    floor_area_m2=len(cells) * STEP ** 2, wall_thickness_m=WALL_THICKNESS,
                    regions=regions(), starts=STARTS,
                    evaluation_note='Union the floor rectangles; do not sum overlaps. This is geometry, not a prior for robots.')
    return {'long_t.sdf': world_xml(), 'overview.svg': overview_svg(),
            'geometry.json': json.dumps(metadata, indent=2) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify generated artifacts without writing')
    args = parser.parse_args()
    for name, content in artifacts().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Out of date: {path}')
        else:
            path.write_text(content)
    print(f'long_t: {len(floor_cells()) * STEP ** 2:g} m² nominal floor; artifacts {"verified" if args.check else "written"}')


if __name__ == '__main__':
    main()
